(ns cljnix.build-test
  (:require
    [clojure.test :refer [deftest is testing]]
    [clojure.string :as str]
    [babashka.fs :as fs]
    [cljnix.build :as build]))

(deftest remove-timestamp-test
  (testing "remove-timestamp! drops the comment lines Maven writes into pom.properties"
    (fs/with-temp-dir [root-dir {:prefix "timestamp_project"}]
      (let [meta-dir (fs/path root-dir "META-INF" "maven" "test" "lib")
            pom-props (fs/path meta-dir "pom.properties")]
        (fs/create-dirs meta-dir)
        (spit (str pom-props)
              (str "#Generated by Maven\n"
                   "#Wed Jan 01 00:00:00 UTC 2020\n"
                   "version=1.0.0\n"
                   "groupId=test\n"
                   "artifactId=lib\n"))
        (build/remove-timestamp! (str root-dir) "test/lib")
        (let [lines (str/split-lines (slurp (str pom-props)))]
          (is (= ["version=1.0.0" "groupId=test" "artifactId=lib"]
                 lines)))))))
